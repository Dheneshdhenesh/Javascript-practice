let num1 = 10;
let operator = "-";
let num2 = 5;

if (operator === "+") {
    console.log("Answer:", num1 + num2);
}
else if (operator === "-") {
    console.log("Answer:", num1 - num2);
}
else if (operator === "*") {
    console.log("Answer:", num1 * num2);
}
else if (operator === "/") {
    console.log("Answer:", num1 / num2);
}
else {
    console.log("Invalid operator");
}



